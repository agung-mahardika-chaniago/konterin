-- Invoices, immutable invoice item snapshots, and payments.
CREATE TABLE invoices (
    id                uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id         uuid NOT NULL REFERENCES tenants (id) ON DELETE RESTRICT,
    outlet_id         uuid NOT NULL REFERENCES outlets (id) ON DELETE RESTRICT,
    service_order_id  uuid NOT NULL REFERENCES service_orders (id) ON DELETE CASCADE,
    invoice_no        varchar(40) NOT NULL,
    customer_id       uuid NOT NULL REFERENCES customers (id) ON DELETE RESTRICT,
    status            varchar(15) NOT NULL DEFAULT 'draft',
    subtotal_service  bigint NOT NULL DEFAULT 0,
    subtotal_part     bigint NOT NULL DEFAULT 0,
    discount_type     varchar(10) NOT NULL DEFAULT 'amount',
    discount_value    bigint NOT NULL DEFAULT 0,
    discount_amount   bigint NOT NULL DEFAULT 0,
    tax_amount        bigint NOT NULL DEFAULT 0,
    total_amount      bigint NOT NULL DEFAULT 0,
    paid_amount       bigint NOT NULL DEFAULT 0,
    remaining_amount  bigint GENERATED ALWAYS AS (total_amount - paid_amount) STORED,
    issued_at         timestamptz,
    due_at            timestamptz,
    notes             text,
    void_reason       text,
    voided_by         uuid REFERENCES users (id) ON DELETE SET NULL,
    voided_at         timestamptz,
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_invoices_tenant_no UNIQUE (tenant_id, invoice_no),
    CONSTRAINT uq_invoices_service_order UNIQUE (service_order_id),
    CONSTRAINT chk_invoices_status CHECK (status IN ('draft', 'unpaid', 'partial', 'paid', 'void')),
    CONSTRAINT chk_invoices_discount_type CHECK (discount_type IN ('amount', 'percent')),
    CONSTRAINT chk_invoices_subtotal_service CHECK (subtotal_service >= 0),
    CONSTRAINT chk_invoices_subtotal_part CHECK (subtotal_part >= 0),
    CONSTRAINT chk_invoices_discount_value CHECK (discount_value >= 0),
    CONSTRAINT chk_invoices_discount_amount CHECK (discount_amount >= 0),
    CONSTRAINT chk_invoices_tax_amount CHECK (tax_amount >= 0),
    CONSTRAINT chk_invoices_total_amount CHECK (total_amount >= 0),
    CONSTRAINT chk_invoices_paid_amount CHECK (paid_amount >= 0),
    CONSTRAINT chk_invoices_paid_not_over_total CHECK (paid_amount <= total_amount),
    CONSTRAINT chk_invoices_discount_not_over_subtotal
        CHECK (discount_amount <= subtotal_service + subtotal_part)
);

CREATE TABLE invoice_items (
    id                    uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id             uuid NOT NULL REFERENCES tenants (id) ON DELETE RESTRICT,
    invoice_id            uuid NOT NULL REFERENCES invoices (id) ON DELETE CASCADE,
    service_order_item_id uuid REFERENCES service_order_items (id) ON DELETE SET NULL,
    item_type             varchar(15) NOT NULL,
    sparepart_id          uuid REFERENCES spareparts (id) ON DELETE SET NULL,
    description           varchar(200) NOT NULL,
    qty                   numeric(12,2) NOT NULL,
    unit_price            bigint NOT NULL,
    cost_price            bigint NOT NULL DEFAULT 0,
    discount_amount       bigint NOT NULL DEFAULT 0,
    subtotal              bigint NOT NULL,
    warranty_days         smallint NOT NULL DEFAULT 0,
    created_at            timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT chk_invoice_items_type CHECK (item_type IN ('service', 'sparepart', 'custom')),
    CONSTRAINT chk_invoice_items_qty CHECK (qty > 0),
    CONSTRAINT chk_invoice_items_unit_price CHECK (unit_price >= 0),
    CONSTRAINT chk_invoice_items_cost_price CHECK (cost_price >= 0),
    CONSTRAINT chk_invoice_items_discount CHECK (discount_amount >= 0),
    CONSTRAINT chk_invoice_items_subtotal CHECK (subtotal >= 0),
    CONSTRAINT chk_invoice_items_warranty CHECK (warranty_days >= 0)
);

CREATE TABLE payments (
    id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id     uuid NOT NULL REFERENCES tenants (id) ON DELETE RESTRICT,
    outlet_id     uuid NOT NULL REFERENCES outlets (id) ON DELETE RESTRICT,
    invoice_id    uuid NOT NULL REFERENCES invoices (id) ON DELETE CASCADE,
    payment_no    varchar(40) NOT NULL,
    method        varchar(20) NOT NULL,
    amount        bigint NOT NULL,
    paid_at       timestamptz NOT NULL DEFAULT now(),
    reference_no  varchar(80),
    proof_path    varchar(255),
    notes         text,
    status        varchar(10) NOT NULL DEFAULT 'posted',
    received_by   uuid REFERENCES users (id) ON DELETE SET NULL,
    voided_by     uuid REFERENCES users (id) ON DELETE SET NULL,
    voided_at     timestamptz,
    void_reason   text,
    created_at    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_payments_tenant_no UNIQUE (tenant_id, payment_no),
    CONSTRAINT chk_payments_method CHECK (method IN ('cash', 'bank_transfer', 'qris', 'card', 'other')),
    CONSTRAINT chk_payments_amount CHECK (amount > 0),
    CONSTRAINT chk_payments_status CHECK (status IN ('posted', 'void'))
);
