-- Service orders and the pre-invoice item lines.
CREATE TABLE service_orders (
    id                       uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id                uuid NOT NULL REFERENCES tenants (id) ON DELETE RESTRICT,
    outlet_id                uuid NOT NULL REFERENCES outlets (id) ON DELETE RESTRICT,
    ticket_no                varchar(40) NOT NULL,
    public_token             char(32),
    public_token_expires_at  timestamptz,
    customer_id              uuid NOT NULL REFERENCES customers (id) ON DELETE RESTRICT,
    device_id                uuid REFERENCES devices (id) ON DELETE SET NULL,
    assigned_technician_id   uuid REFERENCES users (id) ON DELETE SET NULL,
    status                   varchar(30) NOT NULL DEFAULT 'received',
    priority                 varchar(10) NOT NULL DEFAULT 'normal',
    device_brand             varchar(60) NOT NULL,
    device_model             varchar(100) NOT NULL,
    device_imei              varchar(20),
    device_color             varchar(40),
    completeness             text,
    physical_condition       text,
    complaint                text NOT NULL,
    notes                    text,
    internal_notes           text,
    estimated_cost           bigint NOT NULL DEFAULT 0,
    estimated_done_at        timestamptz,
    received_at              timestamptz NOT NULL DEFAULT now(),
    started_at               timestamptz,
    completed_at             timestamptz,
    picked_up_at             timestamptz,
    cancelled_at             timestamptz,
    cancel_reason            text,
    credential_type          varchar(10) NOT NULL DEFAULT 'none',
    credential_enc           bytea,
    credential_key_version   smallint,
    credential_set_at        timestamptz,
    credential_purge_at      timestamptz,
    created_by               uuid REFERENCES users (id) ON DELETE SET NULL,
    updated_by               uuid REFERENCES users (id) ON DELETE SET NULL,
    created_at               timestamptz NOT NULL DEFAULT now(),
    updated_at               timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_service_orders_tenant_ticket UNIQUE (tenant_id, ticket_no),
    CONSTRAINT uq_service_orders_public_token UNIQUE (public_token),
    CONSTRAINT chk_service_orders_status CHECK (status IN (
        'received', 'waiting_diagnosis', 'waiting_approval', 'waiting_part',
        'in_progress', 'testing', 'completed', 'ready_for_pickup',
        'picked_up', 'cancelled'
    )),
    CONSTRAINT chk_service_orders_priority CHECK (priority IN ('normal', 'express')),
    CONSTRAINT chk_service_orders_estimated_cost CHECK (estimated_cost >= 0),
    CONSTRAINT chk_service_orders_picked_up CHECK (picked_up_at IS NULL OR completed_at IS NOT NULL),
    CONSTRAINT chk_service_orders_credential_type
        CHECK (credential_type IN ('none', 'pin', 'password', 'pattern')),
    CONSTRAINT chk_service_orders_credential_pair CHECK (
        (credential_type = 'none' AND credential_enc IS NULL)
        OR (credential_type <> 'none' AND credential_enc IS NOT NULL AND credential_set_at IS NOT NULL)
    )
);

CREATE TABLE service_order_items (
    id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id        uuid NOT NULL REFERENCES tenants (id) ON DELETE RESTRICT,
    service_order_id uuid NOT NULL REFERENCES service_orders (id) ON DELETE CASCADE,
    item_type        varchar(15) NOT NULL,
    sparepart_id     uuid REFERENCES spareparts (id) ON DELETE SET NULL,
    description      varchar(200) NOT NULL,
    qty              numeric(12,2) NOT NULL,
    unit_price       bigint NOT NULL,
    cost_price       bigint NOT NULL DEFAULT 0,
    discount_amount  bigint NOT NULL DEFAULT 0,
    subtotal         bigint NOT NULL,
    warranty_days    smallint NOT NULL DEFAULT 0,
    added_by         uuid REFERENCES users (id) ON DELETE SET NULL,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT chk_service_order_items_type CHECK (item_type IN ('service', 'sparepart', 'custom')),
    CONSTRAINT chk_service_order_items_qty CHECK (qty > 0),
    CONSTRAINT chk_service_order_items_unit_price CHECK (unit_price >= 0),
    CONSTRAINT chk_service_order_items_cost_price CHECK (cost_price >= 0),
    CONSTRAINT chk_service_order_items_discount CHECK (discount_amount >= 0),
    CONSTRAINT chk_service_order_items_subtotal CHECK (subtotal >= 0),
    CONSTRAINT chk_service_order_items_warranty CHECK (warranty_days >= 0)
);
